def platform_key(name: str) -> str:
    """Какая это площадка по названию канала: «Яндекс», «Я.Путешествия», «Яндекс Путешествия» → yandex."""
    low = (name or "").strip().lower()
    for key, info in PLATFORMS.items():
        if any(word in low for word in info["keywords"]):
            return key
    return ""


def guide(name: str) -> dict:
    key = platform_key(name)
    info = PLATFORMS.get(key)
    return {
        "key": key,
        "title": info["name"] if info else (name or "площадку"),
        "steps": info["steps"] if info else GENERIC_STEPS,
        "notes": info["notes"] if info else [],
    }
